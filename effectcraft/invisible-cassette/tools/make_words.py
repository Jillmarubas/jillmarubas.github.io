#!/usr/bin/env python3
"""Regenerate words.jsx (per-scene word timings for at() in kit2.jsx) from the remotion words.json.
Usage: python3 -I tools/make_words.py   (run from effectcraft/invisible-cassette)"""
import json, os, re
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
w = json.load(open(os.path.join(HERE, "../../remotion/src/invisible-cassette/words.json")))
out = {k: [[re.sub(r"[^a-z0-9.$%]", "", x["w"].lower()), round(x["s"], 2)] for x in v] for k, v in w.items()}
js = "// Generated by tools/make_words.py from remotion/src/invisible-cassette/words.json: per scene, [normalised word, VO start s].\n"
js += "var WORDS = " + json.dumps(out, separators=(",", ":")) + ";\n"
js += '''// time (VO seconds) of the first word starting with `word` at or after `after`; a phrase matches word by word.
// Named WT because lib.jsx already uses W for the frame width.
function WT(scene, phrase, after) {
  var ws = WORDS[String(scene)], p = phrase.toLowerCase().split(" ");
  for (var i = 0; i < ws.length; i++) {
    if (ws[i][1] < (after || 0)) continue;
    var ok = true;
    for (var k = 0; k < p.length; k++) { var x = ws[i + k]; if (!x || x[0].indexOf(p[k].replace(/[^a-z0-9.$%]/g, "")) !== 0) { ok = false; break; } }
    if (ok) return ws[i][1];
  }
  throw new Error("word not found in scene " + scene + ": " + phrase + " after " + after);
}
'''
open(os.path.join(HERE, "words.jsx"), "w").write(js)
print("wrote words.jsx")
