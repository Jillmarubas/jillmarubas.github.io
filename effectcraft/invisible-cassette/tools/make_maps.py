#!/usr/bin/env python3
"""Build maps.jsx: map outlines from Natural Earth (public domain), projected and fitted to the frame.

Usage: python3 -I tools/make_maps.py <dir with ne_10m_admin_1_states_provinces.geojson and ne_50m_admin_0_countries.geojson>
Each map: regions (name -> list of polygons as [[x, y], ...] in 1920x1080 comp pixels), points (name -> [x, y]).
Projection: equirectangular with longitude scaled by cos(mid-latitude), fitted into a box, simplified to
about 2 px so the shape paths stay light.
"""
import json, math, os, sys

D = sys.argv[1]
adm1 = json.load(open(os.path.join(D, "ne_10m_admin_1_states_provinces.geojson")))["features"]
adm0 = json.load(open(os.path.join(D, "ne_50m_admin_0_countries.geojson")))["features"]


def polys(geom):
    if geom["type"] == "Polygon":
        return [geom["coordinates"][0]]
    return [p[0] for p in geom["coordinates"]]


def state(admin, name):
    for f in adm1:
        p = f["properties"]
        if p.get("admin") == admin and p.get("name") == name:
            return polys(f["geometry"])
    raise SystemExit(f"no {admin}/{name}")


def country(name):
    for f in adm0:
        if f["properties"].get("ADMIN") == name or f["properties"].get("NAME") == name:
            return polys(f["geometry"])
    raise SystemExit(f"no {name}")


def simplify(pts, tol):
    if len(pts) < 4: return pts
    out = [pts[0]]
    for p in pts[1:]:
        if math.hypot(p[0] - out[-1][0], p[1] - out[-1][1]) >= tol: out.append(p)
    return out if len(out) >= 3 else pts


def build(regions, points, box, bbox=None, min_area=0.0):
    allp = [pt for ps in regions.values() for poly in ps for pt in poly]
    lons = [p[0] for p in allp]; lats = [p[1] for p in allp]
    lo0, lo1, la0, la1 = bbox or (min(lons), max(lons), min(lats), max(lats))
    k = math.cos(math.radians((la0 + la1) / 2))
    w, h = (lo1 - lo0) * k, (la1 - la0)
    bx, by, bw, bh = box
    s = min(bw / w, bh / h)
    ox, oy = bx + (bw - w * s) / 2, by + (bh - h * s) / 2
    proj = lambda lon, lat: [round(ox + (lon - lo0) * k * s, 1), round(oy + (la1 - lat) * s, 1)]
    out = {"regions": {}, "points": {}}
    for name, ps in regions.items():
        keep = []
        for poly in ps:
            q = [proj(*pt) for pt in poly if lo0 - 2 <= pt[0] <= lo1 + 2 and la0 - 2 <= pt[1] <= la1 + 2]
            if len(q) < 3: continue
            xs = [p[0] for p in q]; ys = [p[1] for p in q]
            if (max(xs) - min(xs)) * (max(ys) - min(ys)) < min_area: continue
            keep.append(simplify(q, 2.0))
        out["regions"][name] = keep
    for name, (lat, lon) in points.items():
        out["points"][name] = proj(lon, lat)
    return out


M = {}
# South Australia, 28 Sept 2016: the state and its neighbour Victoria (the interconnectors run between them)
M["sa"] = build({"South Australia": state("Australia", "South Australia"), "Victoria": state("Australia", "Victoria")},
                {"Adelaide": (-34.93, 138.60),
                 # the Heywood interconnector (South East substation, SA -> Heywood, VIC), per AEMO's report
                 "South East": (-37.75, 140.78), "Heywood": (-38.13, 141.63),
                 # lines north of Adelaide where the storm brought towers down (AEMO), drawn schematically
                 "Davenport": (-32.48, 137.80), "Mid North": (-33.70, 138.35),
                 # wind areas: mid north and south east (schematic positions for the icons)
                 "Wind 1": (-33.05, 138.75), "Wind 2": (-33.55, 138.95), "Wind 3": (-34.0, 138.75), "Wind 4": (-37.35, 140.4)},
                (260, 200, 1400, 760))
# 14 Aug 2003: the areas the U.S.-Canada task force lists as blacked out, plus neighbours for context
out2003 = ["Ohio", "Michigan", "Pennsylvania", "New York", "New Jersey", "Connecticut", "Massachusetts", "Vermont"]
ctx = ["Indiana", "West Virginia", "Maryland", "Delaware", "Rhode Island", "New Hampshire", "Maine", "Kentucky", "Illinois", "Wisconsin", "Virginia"]
reg = {n: state("United States of America", n) for n in out2003 + ctx}
reg["Ontario"] = state("Canada", "Ontario"); reg["Quebec"] = state("Canada", "Québec")
M["ne2003"] = build(reg, {"Ohio control room": (41.08, -81.52)}, (180, 220, 1560, 760), bbox=(-90.5, -66.5, 37.5, 47.5), min_area=6)
M["ne2003"]["out"] = out2003 + ["Ontario"]
# Great Britain (9 Aug 2019) and London (the trader, Scene 2)
M["gb"] = build({"United Kingdom": country("United Kingdom")}, {"London": (51.507, -0.128)}, (560, 150, 800, 860), bbox=(-8.5, 2.0, 49.8, 59.0), min_area=20)
# the Netherlands and Rotterdam (Scene 7)
M["nl"] = build({"Netherlands": country("Netherlands")}, {"Rotterdam": (51.92, 4.48)}, (560, 220, 800, 700), bbox=(3.2, 7.3, 50.7, 53.6), min_area=20)
js = "// Generated by tools/make_maps.py from Natural Earth (public domain): 1:10m admin-1 and 1:50m countries.\nvar MAPS = " + json.dumps(M, separators=(",", ":")) + ";\n"
open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "maps.jsx"), "w").write(js)
print({k: {r: len(v) for r, v in m["regions"].items()} for k, m in M.items()})
